-- V1: initial schema for GEDA IIoT SCADA SaaS demo slice (PostgreSQL / Supabase)

CREATE TABLE role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE org_unit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    type VARCHAR(20) NOT NULL,
    parent_id BIGINT NULL,
    code VARCHAR(50) NULL,
    CONSTRAINT chk_org_unit_type CHECK (type IN ('STATE', 'DISCOM', 'DIVISION', 'PLANT')),
    CONSTRAINT fk_org_unit_parent FOREIGN KEY (parent_id) REFERENCES org_unit (id)
);

CREATE INDEX idx_org_unit_parent_id ON org_unit (parent_id);

-- Named app_user (not "user") since USER is a reserved word in PostgreSQL.
CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NULL,
    phone VARCHAR(30) NULL,
    role_id BIGINT NOT NULL,
    org_unit_id BIGINT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    mfa_required BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_user_role FOREIGN KEY (role_id) REFERENCES role (id),
    CONSTRAINT fk_user_org_unit FOREIGN KEY (org_unit_id) REFERENCES org_unit (id)
);

CREATE INDEX idx_user_role_id ON app_user (role_id);
CREATE INDEX idx_user_org_unit_id ON app_user (org_unit_id);

CREATE TABLE device (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    type VARCHAR(20) NOT NULL,
    org_unit_id BIGINT NULL,
    status VARCHAR(20) NOT NULL,
    uptime_percent DECIMAL(5,2) NULL,
    tls_cert_valid_until DATE NULL,
    tls_cert_status VARCHAR(20) NULL,
    created_at TIMESTAMP NOT NULL,
    last_seen_at TIMESTAMP NULL,
    CONSTRAINT chk_device_type CHECK (type IN ('SOLAR_RMS', 'WIND_RMS', 'HYBRID_RMS')),
    CONSTRAINT chk_device_status CHECK (status IN ('ONLINE', 'WARNING', 'OFFLINE')),
    CONSTRAINT chk_device_cert_status CHECK (tls_cert_status IS NULL OR tls_cert_status IN ('VALID', 'EXPIRING', 'EXPIRED')),
    CONSTRAINT fk_device_org_unit FOREIGN KEY (org_unit_id) REFERENCES org_unit (id)
);

CREATE INDEX idx_device_org_unit_id ON device (org_unit_id);
CREATE INDEX idx_device_status ON device (status);

CREATE TABLE generation_reading (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_unit_id BIGINT NULL,
    device_id BIGINT NULL,
    reading_hour TIMESTAMP NOT NULL,
    kwh DECIMAL(12,3) NOT NULL,
    CONSTRAINT fk_generation_reading_org_unit FOREIGN KEY (org_unit_id) REFERENCES org_unit (id),
    CONSTRAINT fk_generation_reading_device FOREIGN KEY (device_id) REFERENCES device (id)
);

CREATE INDEX idx_generation_reading_hour ON generation_reading (reading_hour);
CREATE INDEX idx_generation_reading_org_unit_id ON generation_reading (org_unit_id);
CREATE INDEX idx_generation_reading_device_id ON generation_reading (device_id);

CREATE TABLE alert (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NULL,
    org_unit_id BIGINT NULL,
    severity VARCHAR(10) NOT NULL,
    message VARCHAR(500) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    acknowledged BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_alert_severity CHECK (severity IN ('HIGH', 'MED', 'LOW')),
    CONSTRAINT fk_alert_device FOREIGN KEY (device_id) REFERENCES device (id),
    CONSTRAINT fk_alert_org_unit FOREIGN KEY (org_unit_id) REFERENCES org_unit (id)
);

CREATE INDEX idx_alert_created_at ON alert (created_at);
CREATE INDEX idx_alert_severity ON alert (severity);
CREATE INDEX idx_alert_device_id ON alert (device_id);
CREATE INDEX idx_alert_org_unit_id ON alert (org_unit_id);
